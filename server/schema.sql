-- Great Lakes Wills & Estate — database schema (PostgreSQL / Supabase).
-- Safe to run more than once. The server also runs it on start.
--
-- Security: every table has row level security turned ON with no policies, and the
-- Supabase "anon" and "authenticated" roles are given no privileges. Browsers can't
-- read or write these tables through Supabase's API; only the server (connecting as
-- the database owner through DATABASE_URL) can.

CREATE TABLE IF NOT EXISTS app_meta (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
  id TEXT PRIMARY KEY,                  -- Supabase auth user id
  email TEXT NOT NULL UNIQUE,           -- stored lowercase
  name TEXT NOT NULL DEFAULT '',
  role TEXT NOT NULL DEFAULT 'client' CHECK (role IN ('client', 'attorney')),
  totp_secret TEXT,
  totp_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS sessions (
  token TEXT PRIMARY KEY,               -- SHA-256 of the cookie value
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  stage TEXT NOT NULL DEFAULT 'full',   -- 'totp' = email code checked, authenticator code still needed
  expires_at TIMESTAMPTZ NOT NULL
);

-- Attempt counters for sign-in and other abuse-prone actions. Kept in the database
-- (not memory) because the site runs on several short-lived servers at once.
CREATE TABLE IF NOT EXISTS rate_limits (
  key TEXT PRIMARY KEY,
  count INTEGER NOT NULL,
  reset_at TIMESTAMPTZ NOT NULL
);

-- Used only when Supabase isn't configured (local development and tests).
CREATE TABLE IF NOT EXISTS email_codes (
  email TEXT PRIMARY KEY,
  code_hash TEXT NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS matters (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users(id),
  status TEXT NOT NULL DEFAULT 'draft',
  answers TEXT NOT NULL DEFAULT '{}',
  evaluation TEXT,
  price_cents INTEGER,
  engagement_accepted_at TIMESTAMPTZ,
  engagement_ip TEXT,
  engagement_version TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  paid_at TIMESTAMPTZ,
  approved_at TIMESTAMPTZ,
  approved_by TEXT REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS idx_matters_user ON matters(user_id);
CREATE INDEX IF NOT EXISTS idx_matters_status ON matters(status);

CREATE TABLE IF NOT EXISTS payments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  matter_id INTEGER NOT NULL REFERENCES matters(id),
  provider TEXT NOT NULL,
  provider_ref TEXT,
  amount_cents INTEGER NOT NULL,
  status TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reviews (
  matter_id INTEGER PRIMARY KEY REFERENCES matters(id),
  checklist TEXT NOT NULL DEFAULT '{}',
  notes TEXT NOT NULL DEFAULT '',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS messages (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  matter_id INTEGER NOT NULL REFERENCES matters(id),
  author_id TEXT NOT NULL REFERENCES users(id),
  body TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Files live in private storage; these rows record where.
CREATE TABLE IF NOT EXISTS revised_docs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  matter_id INTEGER NOT NULL REFERENCES matters(id),
  doc_id TEXT NOT NULL,
  filename TEXT NOT NULL,
  storage_path TEXT NOT NULL,
  uploaded_by TEXT NOT NULL REFERENCES users(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS uploads (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  matter_id INTEGER NOT NULL REFERENCES matters(id),
  filename TEXT NOT NULL,
  mime TEXT NOT NULL,
  size INTEGER NOT NULL DEFAULT 0,
  storage_path TEXT NOT NULL,
  uploaded_by TEXT NOT NULL REFERENCES users(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  matter_id INTEGER REFERENCES matters(id),
  actor_id TEXT REFERENCES users(id),
  action TEXT NOT NULL,
  detail TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

